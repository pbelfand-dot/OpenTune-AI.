"""Render analysis reports as Markdown or JSON-compatible dicts."""

from __future__ import annotations

from dataclasses import asdict

from opentune.analysis.analyzer import AnalysisReport
from opentune.core.models import CHANNELS

_ICON = {"critical": "🔴", "warning": "🟠", "info": "🔵"}

KEY_STATS = ("rpm", "boost", "vehicle_speed", "coolant_temp", "oil_temp", "intake_air_temp",
             "timing_advance", "maf", "lambda_cmd", "battery_voltage")


def to_markdown(report: AnalysisReport) -> str:
    out = [f"# OpenTune AI analysis — {report.engine}", "", report.summary, ""]
    out.append("## Findings")
    if not report.findings:
        out.append("No issues detected by the rule set.")
    for f in report.findings:
        when = f" (t={f.time_s:.1f} s)" if f.time_s is not None else ""
        out.append(f"- {_ICON.get(f.severity, '-')} **{f.severity.upper()}** — {f.title}{when}")
        out.append(f"  - {f.detail}")
        if f.recommendation:
            out.append(f"  - Recommendation: {f.recommendation}")
    out.append("")
    if report.pulls:
        out.append("## Full-throttle pulls")
        out.append("| # | Time (s) | RPM | Peak boost (bar) | Min timing (°) | IAT (°C) | Power (kW) |")
        out.append("|---|---|---|---|---|---|---|")
        for i, p in enumerate(report.pulls, 1):
            power = f"{p.peak_power_kw:.0f}" if p.peak_power_kw else "–"
            out.append(
                f"| {i} | {p.start_s:.1f}–{p.end_s:.1f} | {p.start_rpm:.0f}→{p.end_rpm:.0f} | "
                f"{(p.peak_boost_bar or 0):.2f} | {(p.min_timing_deg or 0):.1f} | "
                f"{(p.iat_start_c or 0):.0f}→{(p.iat_end_c or 0):.0f} | {power} |")
        methods = {p.power_method for p in report.pulls if p.power_method}
        if methods:
            out.append("")
            out.append("Power method: " + "; ".join(sorted(methods)) + ". Estimates only — not a dyno.")
        out.append("")
    stats = [(k, report.stats[k]) for k in KEY_STATS if k in report.stats]
    if stats:
        out.append("## Channel summary")
        out.append("| Channel | Min | Mean | Max | Unit |")
        out.append("|---|---|---|---|---|")
        for key, s in stats:
            ch = CHANNELS[key]
            d = ch.decimals
            out.append(f"| {ch.name} | {s.minimum:.{d}f} | {s.mean:.{d}f} | {s.maximum:.{d}f} | {ch.unit} |")
        out.append("")
    if report.narrative:
        out.append("## AI narrative (local model)")
        out.append(report.narrative)
        out.append("")
    out.append("_Generated by OpenTune AI. Findings from generic OBD-II data indicate possible causes, "
               "not confirmed diagnoses._")
    return "\n".join(out)


def to_dict(report: AnalysisReport) -> dict:
    return asdict(report)
